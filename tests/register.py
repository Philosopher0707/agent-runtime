"""The generator for `REGISTER.md` — the suite as a numbered, categorised projection.

**The page is a projection, not a summary.** Its numbers come from a real collection and its
descriptions are the first line of each test file's own docstring, so nothing in it is a second
copy of the truth that could drift from the first. `tests/test_register.py` re-derives both and
fails when the committed page disagrees, which is what makes "regenerate, do not edit" a fact
rather than an instruction.

This module is not collected by pytest — no `test_` prefix, for the same reason `tests/helpers.py`
is not: a helper must not look like a test.

**It refuses to emit an unsound table**, rather than emitting one and letting the guard complain:
a `|` inside a cell silently splits the row and the page then *looks* complete while being short.
"""

from __future__ import annotations

import argparse
import ast
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime
from functools import lru_cache
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REGISTER_PATH = REPO_ROOT / "REGISTER.md"
TESTS_DIR = REPO_ROOT / "tests"

BANNER = (
    "<!-- GENERATED — do not edit this file. Edit tests/register.py, then run `make register`. -->"
)

#: The longest a cited description may be before it is cut. Long enough for the longest real
#: docstring line, short enough to keep the table readable.
MAX_PINS_CHARS = 96

#: The one line in the page that is a property of *when* rather than of *what*. The guard
#: normalises it on both sides — and only it, because a second unchecked line would be a second
#: thing that could be wrong without anyone noticing.
TAKEN = re.compile(r"^_Taken .*$", re.MULTILINE)

#: `tests/test_tools.py::test_x` — one collected case, as pytest lists them.
NODE_ID = re.compile(r"^(tests/test_[a-z_0-9]+\.py)::", re.MULTILINE)
#: `553 tests collected in 0.79s` — pytest's own total, which must agree with the node ids.
REPORTED_TOTAL = re.compile(r"^(\d+) tests? collected", re.MULTILINE)


class RegisterError(Exception):
    """The register cannot be emitted as it stands."""


@dataclass(frozen=True)
class Category:
    number: int
    name: str
    meaning: str
    files: tuple[str, ...]


@dataclass(frozen=True)
class Row:
    number: str
    file: str
    tests: int
    pins: str


@dataclass(frozen=True)
class Section:
    category: Category
    rows: tuple[Row, ...]

    @property
    def tests(self) -> int:
        return sum(row.tests for row in self.rows)


@dataclass(frozen=True)
class Register:
    sections: tuple[Section, ...]
    collected: int
    taken: str

    @property
    def file_count(self) -> int:
        return sum(len(section.rows) for section in self.sections)

    @property
    def total(self) -> int:
        return sum(section.tests for section in self.sections)


